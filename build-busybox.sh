#!/bin/sh
# Build BusyBox 1.36.1, static, i386, trimmed for the CodePaws v86 image.
# Strategy: allnoconfig, then enable exactly the applet/feature set below.
# Run from ~/workspace/v86-image-build/.
set -e
cd "$(dirname "$0")/src/busybox-1.36.1"

make allnoconfig >/dev/null

enable="
STATIC LONG_OPTS PLATFORM_LINUX FEATURE_HUMAN_READABLE
ASH FEATURE_SH_IS_ASH ASH_JOB_CONTROL ASH_ALIAS ASH_GETOPTS ASH_BUILTIN_ECHO
ASH_BUILTIN_PRINTF ASH_BUILTIN_TEST ASH_EXPAND_PRMT ASH_RANDOM_SUPPORT ASH_SLEEP
FEATURE_EDITING FEATURE_TAB_COMPLETION FEATURE_EDITING_FANCY_PROMPT
FEATURE_EDITING_SAVEHISTORY
CAT CHGRP CHMOD CHOWN CP CUT DATE DD DF DIRNAME DU ECHO ENV PRINTENV EXPR FALSE
HEAD HOSTNAME ID KILL LN LS MKDIR MKFIFO MKNOD MV PRINTF PWD READLINK REALPATH
RM RMDIR SEQ SLEEP SORT STAT STTY SYNC TAIL TEE TEST TOUCH TR TRUE TTY UNAME
UNIQ WC WHOAMI XARGS YES BASENAME CLEAR GETOPT MKTEMP
FEATURE_LS_FILETYPES FEATURE_LS_RECURSIVE FEATURE_LS_SORTFILES FEATURE_LS_TIMESTAMPS
FEATURE_LS_USERNAME FEATURE_DATE_ISOFMT
GREP FEATURE_GREP_EGREP_ALIAS FEATURE_GREP_FGREP_ALIAS FEATURE_GREP_CONTEXT
FIND FEATURE_FIND_MAXDEPTH FEATURE_FIND_NEWER FEATURE_FIND_INUM FEATURE_FIND_EXEC
FEATURE_FIND_USER FEATURE_FIND_GROUP FEATURE_FIND_NOT FEATURE_FIND_DEPTH
FEATURE_FIND_PAREN FEATURE_FIND_SIZE FEATURE_FIND_PRUNE FEATURE_FIND_DELETE
FEATURE_FIND_PATH FEATURE_FIND_REGEX FEATURE_FIND_LINKS
TEST1 TEST2 EGREP FGREP ZCAT FEATURE_FIND_TYPE FEATURE_FIND_PERM FEATURE_FIND_MTIME
SED AWK VI FEATURE_VI_COLON FEATURE_VI_YANKMARK FEATURE_VI_SEARCH FEATURE_VI_DOT_CMD
FEATURE_VI_READONLY FEATURE_VI_SETOPTS FEATURE_VI_SET
LESS FEATURE_LESS_BRACKETS FEATURE_LESS_FLAGS FEATURE_LESS_REGEXP FEATURE_LESS_WINCH
MORE
PS TOP FREE UPTIME KILLALL PGREP PKILL PIDOF FEATURE_TOP_CPU_USAGE_PERCENTAGE
FEATURE_TOP_CPU_GLOBAL_PERCENTS
DMESG MOUNT UMOUNT
TAR FEATURE_TAR_CREATE GZIP GUNZIP
MD5SUM SHA256SUM HEXDUMP DIFF CMP WHICH TIMEOUT
SETSID CTTYHACK
"
for sym in $enable; do
  sed -i -E "s/^# CONFIG_${sym} is not set/CONFIG_${sym}=y/; s/^CONFIG_${sym}=n\$/CONFIG_${sym}=y/" .config
done

yes "" | make oldconfig >/dev/null 2>&1 || true
cp .config ../../busybox.config

make -j"$(nproc)" CC="gcc -m32" HOSTCC=gcc busybox
file busybox
rm -rf ../../rootfs
make CONFIG_PREFIX="../../rootfs" CC="gcc -m32" HOSTCC=gcc install
echo "busybox installed into rootfs"
